// Extracts the `@layer tokens { ... }` block (design tokens only, no
// component CSS) from the renderer's own stylesheet, so the docs site
// never forks a parallel set of colours. Run with --check to fail on
// drift instead of writing.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const sourcePath = path.join(repoRoot, "src/presentation/variant-a.css");
const outPath = path.resolve(here, "../src/styles/tokens.generated.css");

const source = readFileSync(sourcePath, "utf8");
const lines = source.split("\n");
const startIdx = lines.findIndex((l) => l.trim() === "@layer tokens {");
if (startIdx === -1) throw new Error("@layer tokens { not found in variant-a.css");

let depth = 0;
let endIdx = -1;
for (let i = startIdx; i < lines.length; i++) {
  for (const ch of lines[i]) {
    if (ch === "{") depth++;
    if (ch === "}") {
      depth--;
      if (depth === 0) {
        endIdx = i;
        break;
      }
    }
  }
  if (endIdx !== -1) break;
}
if (endIdx === -1) throw new Error("unbalanced braces reading @layer tokens");

const block = lines.slice(startIdx, endIdx + 1).join("\n");
const generated =
  "/* GENERATED by scripts/sync-tokens.mjs from src/presentation/variant-a.css.\n" +
  "   Do not hand-edit — rerun the script after the source tokens change. */\n" +
  block +
  "\n";

if (process.argv.includes("--check")) {
  let existing;
  try {
    existing = readFileSync(outPath, "utf8");
  } catch {
    console.error("FAIL: src/styles/tokens.generated.css is missing — run `node scripts/sync-tokens.mjs`.");
    process.exit(1);
  }
  if (existing !== generated) {
    console.error(
      "FAIL: tokens.generated.css has drifted from src/presentation/variant-a.css.\n" +
        "Run `node scripts/sync-tokens.mjs` and commit the diff.",
    );
    process.exit(1);
  }
  console.log("OK: design tokens match src/presentation/variant-a.css.");
} else {
  writeFileSync(outPath, generated);
  console.log(`wrote ${outPath}`);
}
